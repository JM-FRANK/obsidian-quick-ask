const TRANSLATIONS = { en: EN, "zh-CN": ZH_CN };

function languageOf(settingsOrLanguage) {
  if (typeof settingsOrLanguage === "string") return settingsOrLanguage;
  if (settingsOrLanguage?.values) return settingsOrLanguage.values().language ?? DEFAULT_LANGUAGE;
  if (settingsOrLanguage && typeof settingsOrLanguage.language === "string") return settingsOrLanguage.language;
  if (settingsOrLanguage && typeof settingsOrLanguage.language === "function") return settingsOrLanguage.language();
  return DEFAULT_LANGUAGE;
}

function resolveLanguage(settingsOrLanguage) {
  const language = languageOf(settingsOrLanguage);
  return LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;
}

function t(settingsOrLanguage, key, variables = {}) {
  const language = resolveLanguage(settingsOrLanguage);
  const template = TRANSLATIONS[language][key] ?? EN[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}

module.exports = { DEFAULT_LANGUAGE, LANGUAGES, t, resolveLanguage };
